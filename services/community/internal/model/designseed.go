// SeedIfEmpty 空表写入首批拆解（幂等：非空表跳过）。
func (m *DesignModel) SeedIfEmpty() error {
	var count int64
	if err := m.db.QueryRow(`SELECT COUNT(*) FROM design_breakdowns`).Scan(&count); err != nil {
		return fmt.Errorf("统计拆解表失败: %w", err)
	}
	if count > 0 {
		return nil
	}
	for _, b := range seedDesignBreakdowns {
		if _, err := m.Create(b); err != nil {
			return fmt.Errorf("写入拆解种子失败: %w", err)
		}
	}
	return nil
}
