def render(lang, switches):
    L = PAGES[lang]
    lines = [f"# {L['title']}", "", L["intro"], ""]
    lines.append(f"<!-- generated by scripts/config-switch-gifs/render_docs.py; do not edit by hand -->")
    lines.append("")

    order, groups = [], {}
    for s in switches:
        g = s[L["group_key"]]
        if g not in groups:
            groups[g] = []
            order.append(g)
        groups[g].append(s)

    for g in order:
        lines.append(f"## {g}")
        lines.append("")
        for s in groups[g]:
            lines.append(f"<!-- switch: {s['key']} -->")
            lines.append(f"### {s[L['name_key']]}")
            lines.append("")
            lines.append(f"- {L['labels']['config']}: `{s['config']}`")
            lines.append(f"- {L['labels']['captured'] if s['capture'] else L['labels']['manual']}")
            lines.append("")
            lines.append(s[L["effect_key"]])
            lines.append("")
            if s["capture"]:
                lines.append(f"![{s[L['name_key']]}](/config-switch-gifs/{s['key']}.gif)")
                lines.append("")
                lines.append(
                    f"{L['labels']['static']} [{s['key']}-off.png](/config-switch-gifs/{s['key']}-off.png)"
                    f" · [{s['key']}-on.png](/config-switch-gifs/{s['key']}-on.png) · "
                    + L["verified"]
                )
                lines.append("")
        # blank between groups handled by next loop iteration

    lines.append(f"## {L['manual_title']}")
    lines.append("")
    lines.append(L["manual_note"])
    lines.append("")
    for s in switches:
        if not s["capture"]:
            lines.append(f"<!-- switch: {s['key']} -->")
            lines.append(f"- [ ] `{s['config']}`（{s[L['name_key']]}）— " + L["labels"]["manual_item"].format(effect=s[L["effect_key"]]))
    lines.append("")
    lines.append(f"## {L['regen_title']}")
    lines.append("")
    lines.append(L["regen"])
    lines.append("")
    return "\n".join(lines)


def main():
    switches = json.loads((HERE / "switches.json").read_text(encoding="utf-8"))["switches"]
    for lang in ("en", "zh"):
        page = PAGES[lang]
        page["out"].parent.mkdir(parents=True, exist_ok=True)
        page["out"].write_text(render(lang, switches), encoding="utf-8")
        print(f"[docs] {page['out'].relative_to(ROOT)}")
    # generate.py --check 以 `switch: <key>` 注释核对文档覆盖面
    _ = sys.argv
    return 0


if __name__ == "__main__":
    sys.exit(main())
